/**
 * astro-demo build pipeline — Keystatic content → demo data
 *
 * Reads Keystatic demo-sites content from the parent repo and generates
 * a TypeScript data file used by the Astro demo site at build time.
 *
 * Usage: node scripts/build-demo-data.mjs (run before `astro build`)
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs"
import { resolve, dirname } from "node:path"
import { fileURLToPath } from "node:url"
import yaml from "js-yaml"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, "..")
const KEYSTATIC_DIR = resolve(ROOT, "..", "content", "keystatic", "demo-sites")
const OUTPUT_DIR = resolve(ROOT, "src", "data")
const OUTPUT_FILE = resolve(OUTPUT_DIR, "demo-sites.ts")

function parseMdoc(filePath) {
  const raw = readFileSync(filePath, "utf8")
  const parts = raw.split("---\n")
  if (parts.length < 2) return null
  const frontmatter = yaml.load(parts[1])
  return frontmatter
}

function build() {
  if (!existsSync(KEYSTATIC_DIR)) {
    console.warn("[build-demo-data] Keystatic content dir not found:", KEYSTATIC_DIR)
    return
  }

  const demos = []
  const files = readdirSync(KEYSTATIC_DIR).filter(f => f.endsWith(".mdoc"))
  for (const file of files) {
    const data = parseMdoc(resolve(KEYSTATIC_DIR, file))
    if (data && data.status !== "draft" && data.title) {
      demos.push({
        title: data.title,
        customerName: data.customerName || data.title,
        companyId: data.companyId || "",
        domain: data.domain || "",
        industry: data.industry || "consulting",
        accentColor: data.accentColor || "#7c3aed",
        accentColorDark: data.accentColorDark || "#5b21b6",
        status: data.status || "draft",
        heroHeadline: data.heroHeadline || "",
        heroSubtitle: data.heroSubtitle || "",
        serviceTitle: data.serviceTitle || "提供サービス",
        services: Array.isArray(data.services) ? data.services : [],
        caseTitle: data.caseTitle || "導入実績",
        caseDescription: data.caseDescription || "",
        caseMetrics: Array.isArray(data.caseMetrics) ? data.caseMetrics : [],
        ctaTitle: data.ctaTitle || "無料相談",
        ctaBody: data.ctaBody || "",
        calBookingUrl: data.calBookingUrl || "",
      })
    }
  }

  if (!existsSync(OUTPUT_DIR)) mkdirSync(OUTPUT_DIR, { recursive: true })

  const output = `// Auto-generated by scripts/build-demo-data.mjs — do not edit directly
// Source: content/keystatic/demo-sites/*.mdoc

import type { DemoData } from "../keystatic/demo-data"

export const DEMO_SITES: Record<string, DemoData> = {
${demos.map(d => `  "${d.title}": ${JSON.stringify(d, null, 2).replace(/\n/g, "\n  ")}`).join(",\n")}
}

export const DEFAULT_SLUG = "${demos[0]?.title || "default-demo"}"
`
  writeFileSync(OUTPUT_FILE, output, "utf8")
  console.log(`[build-demo-data] Generated ${demos.length} demo sites → ${OUTPUT_FILE}`)
}

build()
