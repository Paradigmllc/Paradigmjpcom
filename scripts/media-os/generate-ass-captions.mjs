import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { validateAndCleanTranscript } from "./validate-transcript.mjs";

const PROFILE_CONFIG = {
  vertical: { width: 1080, height: 1920, fontSize: 68, marginL: 72, marginR: 72, marginV: 285, maxChars: 18, maxLineChars: 11 },
  landscape: { width: 1920, height: 1080, fontSize: 52, marginL: 120, marginR: 120, marginV: 74, maxChars: 38, maxLineChars: 28 },
};

function validatedTranscript(input) {
  const hasValidatedWords = input?.quality?.passed === true
    && Array.isArray(input.words)
    && input.words.every((word) => typeof word?.id === "string" && word.id);
  return hasValidatedWords ? input : validateAndCleanTranscript(input);
}

function captionLength(words, language) {
  const separatorLength = language === "ja" ? 0 : Math.max(0, words.length - 1);
  return words.reduce((total, word) => total + word.text.length, separatorLength);
}

function wrapCaption(words, language, maxLineChars) {
  const separator = language === "ja" ? "" : " ";
  const lines = [];
  let current = "";
  for (const word of words) {
    const candidate = current ? `${current}${separator}${word.text}` : word.text;
    if (current && candidate.length > maxLineChars && lines.length === 0) {
      lines.push(current);
      current = word.text;
    } else {
      current = candidate;
    }
  }
  if (current) lines.push(current);
  return lines.join("\\N");
}

export function groupTranscriptWords(input, options = {}) {
  const transcript = validatedTranscript(input);
  const profile = options.profile ?? "vertical";
  const config = PROFILE_CONFIG[profile];
  if (!config) throw new Error(`Unsupported caption profile: ${profile}`);

  const maxDuration = Number(options.maxDuration ?? 3.5);
  const maxGap = Number(options.maxGap ?? 0.8);
  if (!Number.isFinite(maxDuration) || maxDuration <= 0 || !Number.isFinite(maxGap) || maxGap < 0) {
    throw new Error("Caption maxDuration and maxGap are invalid.");
  }

  const groups = [];
  let current = [];
  const flush = () => {
    if (current.length === 0) return;
    groups.push({
      id: `c-${String(groups.length + 1).padStart(4, "0")}`,
      start: current[0].start,
      end: current.at(-1).end,
      text: wrapCaption(current, transcript.language, config.maxLineChars),
      wordIds: current.map((word) => word.id),
    });
    current = [];
  };

  for (const word of transcript.words) {
    if (current.length > 0) {
      const gap = word.start - current.at(-1).end;
      const duration = word.end - current[0].start;
      const length = captionLength([...current, word], transcript.language);
      if (gap > maxGap || duration > maxDuration || length > config.maxChars) flush();
    }
    current.push(word);
    if (/[。！？!?]$/u.test(word.text)) flush();
  }
  flush();

  return { transcript, profile, config, groups };
}

function assTime(seconds) {
  const centiseconds = Math.max(0, Math.round(Number(seconds) * 100));
  const hours = Math.floor(centiseconds / 360000);
  const minutes = Math.floor((centiseconds % 360000) / 6000);
  const wholeSeconds = Math.floor((centiseconds % 6000) / 100);
  const remainder = centiseconds % 100;
  return `${hours}:${String(minutes).padStart(2, "0")}:${String(wholeSeconds).padStart(2, "0")}.${String(remainder).padStart(2, "0")}`;
}

function escapeAssText(text) {
  return text
    .replaceAll("\\N", "\u0000")
    .replaceAll("\\", "\\\\")
    .replaceAll("{", "\\{")
    .replaceAll("}", "\\}")
    .replaceAll("\u0000", "\\N");
}

export function generateAss(input, options = {}) {
  const grouped = groupTranscriptWords(input, options);
  const { config, groups, transcript } = grouped;
  const events = groups.map((group) => {
    const effect = `mediaos:${group.id}:${group.wordIds.join("|")}`;
    return `Dialogue: 0,${assTime(group.start)},${assTime(group.end)},Default,,0,0,0,${effect},${escapeAssText(group.text)}`;
  });

  const content = [
    "[Script Info]",
    "; Generated by YouTube Media OS. Dialogue Effect fields preserve source word IDs.",
    "ScriptType: v4.00+",
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    `PlayResX: ${config.width}`,
    `PlayResY: ${config.height}`,
    "YCbCr Matrix: TV.709",
    "",
    "[V4+ Styles]",
    "Format: Name,Fontname,Fontsize,PrimaryColour,SecondaryColour,OutlineColour,BackColour,Bold,Italic,Underline,StrikeOut,ScaleX,ScaleY,Spacing,Angle,BorderStyle,Outline,Shadow,Alignment,MarginL,MarginR,MarginV,Encoding",
    `Style: Default,Noto Sans JP,${config.fontSize},&H00F0EDE5,&H00F0EDE5,&H000D1011,&H70000000,-1,0,0,0,100,100,0,0,1,6,2,2,${config.marginL},${config.marginR},${config.marginV},1`,
    "",
    "[Events]",
    "Format: Layer,Start,End,Style,Name,MarginL,MarginR,MarginV,Effect,Text",
    ...events,
    "",
  ].join("\n");

  return {
    content,
    manifest: {
      version: 1,
      language: transcript.language,
      model: transcript.model,
      profile: grouped.profile,
      fontFamily: "Noto Sans JP",
      captions: groups,
    },
  };
}

function parseArgs(argv) {
  const [input, ...rest] = argv;
  const values = { input };
  for (let index = 0; index < rest.length; index += 2) {
    const flag = rest[index];
    const value = rest[index + 1];
    if (!flag?.startsWith("--") || value === undefined) throw new Error(`Invalid argument near ${flag ?? "end of command"}.`);
    values[flag.slice(2)] = value;
  }
  return values;
}

async function main(argv) {
  const args = parseArgs(argv);
  if (!args.input || !args.output) {
    throw new Error("Usage: node scripts/generate-ass-captions.mjs <transcript.json> --output <captions.ass> [--profile vertical|landscape] [--manifest-output captions.json]");
  }
  const input = JSON.parse(await readFile(resolve(args.input), "utf8"));
  const result = generateAss(input, { profile: args.profile });
  const outputPath = resolve(args.output);
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, result.content, "utf8");
  if (args["manifest-output"]) {
    const manifestPath = resolve(args["manifest-output"]);
    await mkdir(dirname(manifestPath), { recursive: true });
    await writeFile(manifestPath, `${JSON.stringify(result.manifest, null, 2)}\n`, "utf8");
  }
  process.stdout.write(`${JSON.stringify({ output: outputPath, captions: result.manifest.captions.length, wordIds: result.manifest.captions.flatMap((caption) => caption.wordIds) }, null, 2)}\n`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
